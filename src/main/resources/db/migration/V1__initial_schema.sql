-- Pulse V1 Initial Schema
-- Tables: users, monitors, check_results, incidents, alert_channels

-- 1. Users Table (Authentication and user management)
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'ROLE_USER',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Monitors Table (URL targets, schedules, and active statuses)
CREATE TABLE monitors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    url VARCHAR(2048) NOT NULL,
    http_method VARCHAR(10) NOT NULL DEFAULT 'GET',
    interval_seconds INT NOT NULL DEFAULT 60 CHECK (interval_seconds >= 10),
    timeout_seconds INT NOT NULL DEFAULT 30 CHECK (timeout_seconds >= 1 AND timeout_seconds <= 120),
    expected_status_code INT NOT NULL DEFAULT 200,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('UP', 'DOWN', 'PENDING', 'PAUSED')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_checked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_monitors_user_id ON monitors(user_id);
CREATE INDEX idx_monitors_active_schedule ON monitors(is_active, last_checked_at);

-- 3. Check Results Table (Detailed ping/health check history)
CREATE TABLE check_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id BIGINT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
    status_code INT,
    response_time_ms INT,
    is_success BOOLEAN NOT NULL,
    error_message TEXT,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_check_results_monitor_id_checked_at ON check_results(monitor_id, checked_at DESC);
CREATE INDEX idx_check_results_checked_at ON check_results(checked_at);

-- 4. Incidents Table (Downtime tracking lifecycle: ongoing, acknowledged, resolved)
CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id BIGINT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
    status VARCHAR(50) NOT NULL DEFAULT 'ONGOING' CHECK (status IN ('ONGOING', 'ACKNOWLEDGED', 'RESOLVED')),
    cause TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    acknowledged_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_incidents_monitor_id ON incidents(monitor_id);
CREATE INDEX idx_incidents_status ON incidents(status);
CREATE INDEX idx_incidents_started_at ON incidents(started_at DESC);

-- 5. Alert Channels Table (Notification delivery channels such as email)
CREATE TABLE alert_channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    monitor_id BIGINT REFERENCES monitors(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(50) NOT NULL DEFAULT 'EMAIL' CHECK (type IN ('EMAIL', 'WEBHOOK')),
    destination VARCHAR(255) NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_alert_channels_user_id ON alert_channels(user_id);
CREATE INDEX idx_alert_channels_monitor_id ON alert_channels(monitor_id);
